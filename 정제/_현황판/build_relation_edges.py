    승격원고 = HERE / "보드승격_원고.jsonl"
    if 승격원고.exists():
        승격 = {}
        for _ln in 승격원고.read_text(encoding="utf-8").split("\n"):
            if not _ln.strip():
                continue
            _d = json.loads(_ln)
            if _d.get("_주석") or not _d.get("a"):
                continue
            승격[(_d["a"], _d["b"], _d["kind"])] = _d
        _n승 = 0
        for e in uniq:
            _d = 승격.get((e["a"], e["b"], e["kind"]))
            if _d and e.get("근거유형") == "보드규칙":
                e["weight"] = 1.0
                e["근거유형"] = "보드규칙·코퍼스확인"
                e["교차축자"] = _d["축자"]
                e["교차para"] = _d.get("para_id")
                _n승 += 1
        print(f"  보드 간선 승격 — {_n승}/{len(승격)} (코퍼스 룰어 일치 · 0.8→1.0)")

    # ══ ★260728 발현 «살» 오버레이 — P2 채굴 + 감독관 눈검수(채택 9 · 보류 6 · 근거없음 6) ══
    #   발현 간선 160 중 효과가 18뿐이라 «합산하면 조용히 틀리는» 층이었다.
    #   원고 = 발현살_원고.jsonl. 처분 3종:
    #     채택   → 효과·축자·para_id·stance를 그 간선에 싣는다 (문장이 방향을 말한 것만)
    #     보류   → 건드리지 않는다 (개별 명식 일반화·조건부 위험 — 사람 확인 큐)
    #     근거없음 → 「근거없음": true」 표시 — **코퍼스 실증 0**인데 관계도 서술만 있는 것.
    #               지우는 게 아니라 라이브에서 단정 문장을 못 쓰게 막는 깃발이다.
    #               (실증: 천을귀인↔구설이 같은 창에 나온 적 0회 — 위조 후보 적발)
    살원고 = HERE / "발현살_원고.jsonl"
    if 살원고.exists():
        살 = {}
        for _ln in 살원고.read_text(encoding="utf-8").split("\n"):
            if not _ln.strip():
                continue
            _d = json.loads(_ln)
            if _d.get("_주석") or not _d.get("a"):
                continue
            살[(_d["a"], _d["b"])] = _d
        _hit = Counter()
        for e in uniq:
            if e["kind"] != "발현":
                continue
            _d = 살.get((e["a"], e["b"]))
            if not _d:
                continue
            if _d["처분"] == "채택":
                e["effect"] = e.get("effect") or ("촉진" if _d["효과"] == "촉진" else "해소")
                e["살축자"] = _d["축자"]
                e["살para"] = _d["para_id"]
                if _d.get("stance") and _d["stance"] != "일치":
                    e["stance"] = e.get("stance") or _d["stance"]
                _hit["채택"] += 1
            elif _d["처분"] == "근거없음":
                e["근거없음"] = True
                e["note"] = (e.get("note") or "") + " ⚠코퍼스 실증 0 — 단정 금지"
                _hit["근거없음"] += 1
        print(f"  발현 살 오버레이 — 채택 {_hit['채택']} · 근거없음 표시 {_hit['근거없음']} · 보류(무접촉) {sum(1 for v in 살.values() if v['처분']=='보류')}")

    out_e = DATA / "relation_edges.jsonl"
    with out_e.open("w", encoding="utf-8") as fh:
        for e in HIER + uniq:
            fh.write(json.dumps(e, ensure_ascii=False) + "\n")

    # ── 노드 속성(layer·음양·오행) 저장
    layers = []
    gan_names = {n for n, _, _, _ in CHEONGAN}
    ji_names = {n for n, _, _, _, _, _ in JIJI}
    for c, (big, mid) in CONCEPTS.items():
        rec = {"concept": c, "big": big, "mid": mid,
               "layer": "S15발현" if big.startswith("S15") else
                        ("골격어" if big.startswith("S14") else "개념")}
        if c in gan_names:
            n, h, oh, ym = next(x for x in CHEONGAN if x[0] == c)
            rec.update({"한자": h, "오행": oh, "음양": ym, "계열": "천간"})
        elif c in ji_names:
            n, h, oh, che, yong, cls = next(x for x in JIJI if x[0] == c)
            rec.update({"한자": h, "오행": oh, "음양_體": che, "음양_用": yong,
                        "분류": cls, "계열": "지지"})
        layers.append(rec)
    out_n = DATA / "node_layers.jsonl"
    with out_n.open("w", encoding="utf-8") as fh:
        for r in layers:
            fh.write(json.dumps(r, ensure_ascii=False) + "\n")

    # ── 리포트
    kinds = Counter(e["kind"] for e in uniq)
    stamp = datetime.now(KST).strftime("%Y-%m-%d %H:%M KST")
    print(f"[관계 간선] {stamp}")
    print(f"  계층 간선   {len(HIER):>5}개  (대주제 {len(TAXONOMY)} → 중주제 "
          f"{sum(len(m) for m in TAXONOMY.values())} → 개념 {len(CONCEPTS)})")
    print(f"  관계 간선   {len(uniq):>5}개  (결정론 규칙 · 축자 아님)")
    for k, v in kinds.most_common():
        print(f"      {k:<8} {v:>4}")
    touched = {e["a"] for e in uniq} | {e["b"] for e in uniq}
    print(f"  관계가 붙은 개념 {len(touched)}/{len(CONCEPTS)}")
    thin = [c for c in CONCEPTS if c not in touched]
    print(f"  ⚠결정론 관계가 하나도 없는 개념 {len(thin)}개 "
          f"— 이건 결함이 아니라 '코퍼스로만 이어지는 개념'이다")
    print(f"     예: {thin[:15]}")
    print(f"  → {out_e}")
    print(f"  → {out_n}")


