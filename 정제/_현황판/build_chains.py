def reduce_derived():
    """각 파생 관계(합·충·원진…)의 실례 쌍이 공리 경로를 갖는지."""
    rep = []
    byk = defaultdict(list)
    for e in L1:
        if e["kind"] in DERIVED:
            byk[e["kind"]].append(e)
    axg = defaultdict(list)
    for e in L1:
        if e["kind"] in AXIOM:
            axg[e["a"]].append((e["b"], e)); axg[e["b"]].append((e["a"], e))

    def axpath(a, b, maxhop=3):
        if a == b:
            return []
        seen, q = {a}, deque([(a, [])])
        while q:
            u, acc = q.popleft()
            if len(acc) >= maxhop:
                continue
            for v, e in axg.get(u, ()):
                if v in seen:
                    continue
                p2 = acc + [e]
                if v == b:
                    return p2
                seen.add(v); q.append((v, p2))
        return None

    for kind, es in sorted(byk.items(), key=lambda t: -len(t[1])):
        ok, bad, ex = 0, 0, []
        for e in es:
            p = axpath(e["a"], e["b"])
            if p:
                ok += 1
                if len(ex) < 2:
                    ex.append(f"{e['a']}·{e['b']} ← " + " · ".join(hop_str(h) for h in p))
            else:
                bad += 1
        rep.append((kind, len(es), ok, bad, ex))
    return rep


