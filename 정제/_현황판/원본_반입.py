def 가리기(text: str) -> str:
    text, n1 = EMAIL.subn("[가림-메일]", text)
    text, n2 = PHONE.subn("[가림-전화]", text)
    text, n3 = HOME_MAC.subn("/Users/[가림-계정]", text)
    text, n4 = HOME_WIN.subn(r"\1[가림-계정]", text)
    # 조직명은 마커도 안 남기고 **통째로 없앤다**(운영자 260727 — "직장명같은건 그냥 아예 없애셈").
    text, n5 = ORG_DRIVE.subn("OneDrive", text)
    계수["메일"] += n1
    계수["전화"] += n2
    계수["경로"] += n3 + n4 + n5
    return text


def 복사(src: Path, dst: Path):
    if src.stat().st_size > GIT_한도:
        계수["생략_대용량"] += 1
        print(f"  ⚠생략(>{GIT_한도 // 1024 // 1024}MB): {src}")
        return
    dst.parent.mkdir(parents=True, exist_ok=True)
    if src.suffix.lower() in TEXT_EXT:
        try:
            dst.write_text(가리기(src.read_text(encoding="utf-8-sig")), encoding="utf-8")
        except UnicodeDecodeError:
            shutil.copyfile(src, dst)
            계수["이진복사"] += 1
    else:
        shutil.copyfile(src, dst)
        계수["이진복사"] += 1
    계수["파일"] += 1


def 트리복사(src_dir: Path, dst_dir: Path, 패턴="*", 평탄화_자막=False, 제외하위=()):
    if not src_dir.exists():
        print(f"  — 없음(건너뜀): {src_dir}")
        return 0
    n = 0
    for p in sorted(src_dir.rglob(패턴)):
        if not p.is_file():
            continue
        rel = p.relative_to(src_dir)
        # 같은 원천 아래 다른 줄이 가져가는 하위(예: 「전사 내용」)는 여기서 건너뛴다
        if 제외하위 and rel.parts and unicodedata.normalize("NFC", rel.parts[0]) in 제외하위:
            continue
        if any(unicodedata.normalize("NFC", part) in 제외 for part in rel.parts):
            continue
        if 평탄화_자막:
            rel = Path(*[unicodedata.normalize("NFC", part).removesuffix("_자막")
                         for part in rel.parts])
        if (dst_dir / rel).exists():          # 겹침(전사본 합류 등) — 이미 들어와 있다
            계수["이미있음"] += 1
            continue
        복사(p, dst_dir / rel)
        n += 1
    return n


def 원천총계(원천: Path):
    """원천의 파일 총수와, 제외 규칙에 걸리는 수. 대차대조표의 좌변이다."""
    총, 걸림 = 0, 0
    for p in 원천.rglob("*"):
        if not p.is_file():
            continue
        총 += 1
        parts = [unicodedata.normalize("NFC", x) for x in p.relative_to(원천).parts]
        if any(x in 제외 for x in parts):
            걸림 += 1
    return 총, 걸림


