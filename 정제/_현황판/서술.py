# -*- coding: utf-8 -*-
"""★서술층 — 관계 사슬을 **사람이 읽는 문장**으로 푼다. 문형(템플릿)은 여기 한 곳에만.

═══ 왜 이 파일이 생겼나 (운영자 260728, 축자) ═══
  *"이런식으로 나올게 아니라, 이게 풀어서 문장으로 나와야되거든 이해되는지
    이거는 정제랑은 또 다른영역인데"*

  앱 두뇌 패널이 「까닭 · 병화(丙) ─비화→ 정화(丁) → …」처럼 **화살표 표기**를
  그대로 내보냈다. 지도(정제)는 맞는데 **화법(서술)**이 없었다 — 도사가 근거를
  «읽어 줄» 수가 없다. 그래서 kind별 결정론 문형을 만들어 빌드 때 문장을 심는다.

═══ 경계 — 정제 원칙이 그대로 관통한다 ═══
  ①**관계를 서술하되 의미(결론)를 서술하지 않는다**(운영자 1-36).
    「극한다」까지가 문장이 되고 「그래서 이혼한다」는 문장이 되면 안 된다.
    import 시 자검(_금칙)이 전 문형을 더미로 렌더해 결론어 혼입을 잡는다.
  ②**밀착(L2)은 밀착이라고 말한다** — 「자주 함께 다뤄진다」이지 인과 문장이 아니다.
  ③**근거없음 깃발 간선은 문장에 유보를 단다** — 단정 문장 금지(260728 발현 살 파도).
  ④문형은 **결정론 템플릿**이라 «적기» 영역이다(창작 아님) — 값은 간선에서만 온다.

⚠새 kind가 생기면 여기 문형을 같이 늘려라. 없으면 문장()이 None을 내고
  build_brain 리포트가 «미문형 kind»로 소리 내어 적는다(조용한 누락 금지).
"""
import re

# ── 조사(助詞) — 받침으로 이/가·은/는·을/를·과/와·으로/로를 가른다 ──────
_PAREN = re.compile(r"\([^)]*\)\s*$")


def _받침(w):
    """표시명 끝 괄호(한자 부연)를 떼고 마지막 한글 음절의 종성 유무를 본다."""
    w = _PAREN.sub("", str(w)).strip() or str(w)
    for ch in reversed(w):
        o = ord(ch)
        if 0xAC00 <= o <= 0xD7A3:
            return (o - 0xAC00) % 28
    return 1   # 한글이 아니면(숫자·라틴) 받침 있는 쪽 — 틀려도 어색할 뿐 뜻은 안 상한다


def 조(w, k):
    j = _받침(w)
    if k == "이":
        return "이" if j else "가"
    if k == "은":
        return "은" if j else "는"
    if k == "을":
        return "을" if j else "를"
    if k == "과":
        return "과" if j else "와"
    if k == "으로":
        return "로" if j in (0, 8) else "으로"   # ㄹ받침은 «로»
    raise KeyError(k)


def _J(w, k):
    return f"{w}{조(w, k)}"


# ── kind별 문형 — 방향(a→b)은 링크망 실측(B5 대표 표본)에서 왔다 ──────
#   소속: 갑목→목 · 구성: 상생→목 · 지장간: 자수→임수 · 롤업: 비겁일반→비견
#   육친: 비겁일반→형제 · 산출: 황도→절기 · 절차: 점수론→월지 · 전제: 십이운성→지지
