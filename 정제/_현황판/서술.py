def _발현(a, b, e):
    """발현 — 효과(촉진/해소)가 부호와 다른 축이라 문장도 갈라 쓴다(260728 효과 배선 계승)."""
    eff = (e or {}).get("effect") or (e or {}).get("효과")
    if eff == "해소":
        s = f"{_J(a, '은')} {_J(b, '을')} 덜어내는 쪽으로 나타나곤 한다."
    elif eff == "촉진":
        s = f"{_J(a, '은')} {_J(b, '을')} 부추기는 쪽으로 나타나곤 한다."
    else:
        s = f"{_J(a, '은')} {_J(b, '으로')} 나타나곤 한다."
    return s


def 문장(e):
    """간선 하나 → 문장 하나. 문형 없는 kind면 None(호출자가 «미문형»으로 센다)."""
    k = e.get("kind") or e.get("관계")
    t = TEMPL.get(k)
    if not t:
        return None
    s = t(e.get("a"), e.get("b"), e)
    # 근거없음 깃발 = 코퍼스 실증 0 — 문장에도 유보를 단다(앱이 단정 못 하게)
    if e.get("근거없음"):
        s += " 다만 상담 기록에서 실제 사례는 아직 확인되지 않았다."
    return s


_고리형 = re.compile(r"^(.+?) ─(.+?)→ (.+)$")


def 사슬문장(hops):
    """근거사슬 hop 목록(고리 문자열 «A ─kind→ B») → 이어 읽는 문장.

    고리를 못 파싱하면 그 고리는 원문 그대로 끼운다 — 조용히 버리지 않는다.
    """
    if not hops:
        return None
    out = []
    for h in hops:
        s = h.get("고리") if isinstance(h, dict) else str(h)
        m = _고리형.match(s or "")
        if m:
            a, k, b = m.group(1), m.group(2), m.group(3)
            t = TEMPL.get(k)
            out.append(t(a, b, {}) if t else s)
        else:
            out.append(s)
    return " ".join(out)


