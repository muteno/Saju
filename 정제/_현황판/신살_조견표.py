# -*- coding: utf-8 -*-
"""
신살 조견표 — 「기준이 있다」가 아니라 **기준 그 자체**를 적는다.

═══ 왜 (260726 감사) ═══
  정의 249건을 훑으니 **9건이 «기준이 있다»만 말하고 기준은 안 적혀** 있었다.
    「천을귀인 : 일간을 **기준으로 정해지는** 대표적 길신…」
  지도의 간선도 마찬가지였다 — 「천을귀인 ─전제→ 일간, 신살 산출 기준 — **일간 기준 조견표**」.
  **그 조견표가 어디에도 없다.**
  산출을 모르면 ①앱이 계산할 수 없고 ②「왜 이 사람에게 천을귀인이 있나」에 답할 수 없다.
  운영자: *"이유를 모르면 연결할 수가 없어 낭설임."*

═══ 왜 «적어 넣기»가 허용되는가 ═══
  페이블 감사역이 그은 경계선(260726):
    **"조견표(입력→글자)까지는 «적기», 글자→삶의 부호(+/−·촉진/해소)부터는 창작이다."**
  조견표는 «갑목 일간이면 축·미가 천을귀인»이라는 **표**다. 해석이 아니다.
  코퍼스에서 캐면 오전사·유파차로 오염된다(8대 교훈: "아는 것을 적어 넣는 도구가 없었다").

═══ 출처 ═══
  `4. 구 사주본_Saju-main/app/src/engine/vendor/sinsal.js`
  **계산 엔진이 이미 갖고 있던 표를 옮겨 적는다.** 새로 만드는 게 아니다.
  → 그래서 `verify_L1_sync.py`가 이 표를 엔진과 대조할 수 있다. 갈라지면 죽는다.

═══ 무엇을 안 적는가 ═══
  ⛔「천을귀인이 있으면 귀인을 만난다」 — 그건 발현이고, 이미 «통설·임상»으로 강등돼 있다.
  ⛔유파가 갈리는 것(도화·역마·화개의 광의/고전 규칙) — `rule` 분기가 있는 것은 stance로 표시.

출력: data/신살조견표.jsonl (사람이 읽는 표) + relation_edges 에 «산출» 간선
"""
import json, sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
DATA = HERE / "data"

GAN = ["갑목(甲)", "을목(乙)", "병화(丙)", "정화(丁)", "무토(戊)",
       "기토(己)", "경금(庚)", "신금(辛)", "임수(壬)", "계수(癸)"]
JI = ["자수(子)", "축토(丑)", "인목(寅)", "묘목(卯)", "진토(辰)", "사화(巳)",
      "오화(午)", "미토(未)", "신금(申)", "유금(酉)", "술토(戌)", "해수(亥)"]

# ══ 엔진 `sinsal.js` 의 표를 그대로 옮긴다 (인덱스: 천간 0갑…9계, 지지 0자…11해)
#    ⚠숫자를 손으로 바꾸지 마라. 엔진과 갈라지면 `verify_L1_sync.py`가 죽는다.
TABLES = {
    # 일간 기준 — 그 일간이면 이 지지가 그 신살이다
    "건록": dict(기준="일간", 표=[2, 3, 5, 6, 5, 6, 8, 9, 11, 0],
                뜻="일간이 가장 힘을 얻는 자리(정록)"),
    "양인": dict(기준="일간", 표={0: 3, 2: 6, 4: 6, 6: 9, 8: 0},
                뜻="양간이 가장 왕성해지는 자리 — **양간에만 있다**"),
    "홍염": dict(기준="일간", 표=[6, 6, 2, 7, 4, 4, 10, 9, 0, 8], 뜻="일간별 홍염 지지"),
    "문창·문곡": dict(기준="일간", 표=[5, 6, 8, 9, 8, 9, 11, 0, 2, 3],
                    표2=[11, 0, 2, 3, 2, 3, 5, 6, 8, 9],
                    뜻="문창(표) · 문곡(표2) — 둘이 다른 자리다"),
    "천을귀인": dict(기준="일간",
                  표=[[1, 7], [0, 8], [11, 9], [11, 9], [1, 7],
                      [0, 8], [1, 7], [6, 2], [5, 3], [5, 3]],
                  뜻="일간마다 **두 자리**다"),
    # 월지 기준
    "천덕·월덕": dict(기준="월지",
                   천덕={2: ("간", 3), 3: ("지", 8), 4: ("간", 8), 5: ("간", 7),
                        6: ("지", 11), 7: ("간", 0), 8: ("간", 9), 9: ("지", 2),
                        10: ("간", 2), 11: ("간", 1), 0: ("지", 5), 1: ("간", 6)},
                   월덕={0: 8, 1: 6, 2: 2, 3: 0},
                   뜻="천덕은 월지→간 또는 지 · 월덕은 월지 삼합→천간"),
}

# 십이신살 — 삼합 기준 순환. 표가 아니라 **규칙**이라 규칙을 적는다.
TWELVE = ["겁살", "재살", "천살", "지살", "년살", "월살",
          "망신살", "장성살", "반안살", "역마살", "육해살", "화개살"]
SAMHAP = {0: "신자진(수)", 1: "사유축(금)", 2: "인오술(화)", 3: "해묘미(목)"}


def samhap_group(b):
    return b % 4


def samhap_wangji(g):
    return (12 - 3 * g) % 12


def twelve_of(base, target):
    start = (samhap_wangji(samhap_group(base)) + 5) % 12   # 겁살 = 왕지+5
    return (target - start + 12) % 12


rows = []
for name, t in TABLES.items():
    if t["기준"] == "일간":
        pairs = []
        tb = t["표"]
        for i, g in enumerate(GAN):
            if isinstance(tb, dict):
                if i not in tb:
                    continue
                pairs.append((g, JI[tb[i]]))
            elif isinstance(tb[i], list):
                pairs.append((g, " · ".join(JI[x] for x in tb[i])))
            else:
                pairs.append((g, JI[tb[i]]))
        rows.append({"신살": name, "기준": "일간", "뜻": t["뜻"],
                     "조견표": [{"일간": a, "자리": b} for a, b in pairs],
                     "출처": "engine/vendor/sinsal.js"})
        if "표2" in t:
            rows.append({"신살": name + "(문곡)", "기준": "일간", "뜻": "문곡 자리",
                         "조견표": [{"일간": GAN[i], "자리": JI[v]}
                                  for i, v in enumerate(t["표2"])],
                         "출처": "engine/vendor/sinsal.js"})
    else:
        rows.append({"신살": name, "기준": "월지", "뜻": t["뜻"],
                     "조견표": [{"월지": JI[m], "천덕": (("천간 " + GAN[v]) if k == "간"
                                                    else ("지지 " + JI[v]))}
                              for m, (k, v) in sorted(t["천덕"].items())],
                     "월덕": [{"월지삼합": SAMHAP[g], "천간": GAN[v]}
                            for g, v in sorted(t["월덕"].items())],
                     "출처": "engine/vendor/sinsal.js"})

# 십이신살 전개 — 기준지(삼합)별 12자리
twelve_rows = []
for g, nm in SAMHAP.items():
    base = samhap_wangji(g)          # 그 그룹의 왕지를 대표 기준지로
    seq = [None] * 12
    for tgt in range(12):
        seq[twelve_of(base, tgt)] = JI[tgt]
    twelve_rows.append({"기준삼합": nm, "자리": dict(zip(TWELVE, seq))})

(DATA / "신살조견표.jsonl").write_text(
    "\n".join(json.dumps(r, ensure_ascii=False) for r in rows + [
        {"신살": "십이신살", "기준": "년지(또는 일지) 삼합",
         "뜻": "겁살 = 삼합 왕지 + 5칸. 거기서 12자리가 순환한다",
         "전개": twelve_rows, "출처": "engine/vendor/sinsal.js"}]) + "\n",
    encoding="utf-8")

# ── 사람이 읽는 표
L = ["# 신살 조견표 — 「기준이 있다」가 아니라 **기준 그 자체**", "",
     "> 정의 감사(260726): 신살 8건이 「일간을 **기준으로 정해지는** 길신」이라고만 하고",
     "> **그 표가 어디에도 없었다.** 산출을 모르면 앱이 계산 못 하고 「왜요?」에도 못 답한다.", "",
     "> 경계선(페이블 260726): **조견표(입력→글자)까지는 «적기», 글자→삶의 부호부터는 창작.**",
     "> 이 파일은 앞쪽이다. 「천을귀인이 있으면 귀인을 만난다」는 여기 없다(그건 통설·임상으로 강등돼 있다).", "",
     "> 출처: 계산 엔진 `engine/vendor/sinsal.js` — **새로 만든 게 아니라 옮겨 적었다.**",
     "> 그래서 `verify_L1_sync.py`가 엔진과 대조할 수 있다. 갈라지면 죽는다.", ""]

for r in rows:
    L += [f"## {r['신살']} <sub>{r['기준']} 기준</sub>", "", f"{r['뜻']}", ""]
    if r["기준"] == "일간":
        L += ["| 일간 | 자리 |", "|---|---|"]
        for x in r["조견표"]:
            L.append(f"| {x['일간']} | {x['자리']} |")
    else:
        L += ["| 월지 | 천덕 |", "|---|---|"]
        for x in r["조견표"]:
            L.append(f"| {x['월지']} | {x['천덕']} |")
        L += ["", "| 월지 삼합 | 월덕 천간 |", "|---|---|"]
        for x in r["월덕"]:
            L.append(f"| {x['월지삼합']} | {x['천간']} |")
    L.append("")

L += ["## 십이신살 <sub>년지(또는 일지) 삼합 기준</sub>", "",
      "겁살 = 그 삼합의 **왕지 + 5칸**. 거기서 12자리가 차례로 돈다.", "",
      "| 기준 삼합 | " + " | ".join(TWELVE) + " |",
      "|---|" + "---|" * 12]
for t in twelve_rows:
    L.append(f"| {t['기준삼합']} | " + " | ".join(t["자리"][k][:2] for k in TWELVE) + " |")
L += ["", "> ⚠**십이신살 기준지가 유파마다 갈린다.** 엔진은 «월·일·시지 → 년지 삼합,",
      "> 년지 → 일지 삼합»(포스텔러 픽스처 역산)을 쓴다. 다른 관법은 년지 하나로만 본다.", ""]

(DATA / "신살조견표.md").write_text("\n".join(L) + "\n", encoding="utf-8")

print(f"신살 조견표 — 표 {len(rows)}종 + 십이신살 4삼합 전개")
for r in rows:
    print(f"   {r['신살']:12s} {r['기준']} 기준 · {len(r['조견표'])}행")
print(f"→ {DATA / '신살조견표.md'}")
