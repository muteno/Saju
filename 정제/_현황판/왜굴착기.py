# ⚠«절기·동지·입춘»은 명리 일상어라 여기 넣으면 안 된다(260728 1차 실행 오탐 539건).
#   바닥 = 주기·각도·천체를 **실제로 말하는** 것만. 단어가 스친 것과 근거가 된 것은 다르다.
천문어 = re.compile(
    r"(목성|세성|공전\s*주기|공전하|자전\s*주기|자전하|황도|태양\s*황경|삭망|"
    r"자전축|23\.5|11\.86|360\s*도|360°|15\s*°|15도로?\s*(나누|등분)|열둘로\s*(나누|등분)|"
    r"열두?\s*(등분|칸으로)|12\s*등분)")
이유없음어 = re.compile(
    r"(후대에?\s*(붙|생|덧)|나중에\s*(붙|갖다)|민간에서|외우기?\s*쉽|기억(술|하기)|"
    r"논형|왕충|이름표|편의상|관습(적)?으로|유래가?\s*(없|불분명|불명)|명리(적)?\s*(의미|역할)(는|은)?\s*없)")


def 종착(문구):
    """이 답변 후보가 바닥인가 — 공리/천문사실/이유없음/(아니면 None=더 파야 함)."""
    if 이유없음어.search(문구):
        return "이유없음"
    if 천문어.search(문구):
        return "천문사실"
    if 공리어.search(문구):
        return "공리"
    return None


