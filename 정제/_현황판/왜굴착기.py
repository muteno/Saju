def main(상한파일=None):
    뿌리 = _코퍼스()
    코퍼스 = 코퍼스적재(뿌리, 상한파일) if 뿌리 else []
    print(f"코퍼스 = {len(코퍼스):,}편 · {sum(len(t) for t,_ in 코퍼스):,}자")

    # 노드 정의 — 백과가 있으면 백과, 없으면 정제본
    노드정의 = {}
    p = DATA / "백과.jsonl"
    if p.exists():
        for l in p.read_text(encoding="utf-8").split("\n"):
            if l.strip() and not l.lstrip().startswith('{"_'):
                r = json.loads(l)
                노드정의[r["concept"]] = r.get("무엇", "")
    p2 = DATA / "정의_정제본.jsonl"
    if p2.exists():
        for l in p2.read_text(encoding="utf-8").split("\n"):
            if l.strip() and not l.lstrip().startswith('{"_'):
                r = json.loads(l)
                노드정의.setdefault(r["concept"], r.get("정의", ""))

    질문들 = []
    for 주어, q, 갈래 in 뿌리질문:                     # ★운영자 드릴을 씨앗으로
        질문들.append({"주어": 주어, "질문": q, "갈래": 갈래, "씨앗": "운영자드릴"})
    for c, d in 노드정의.items():                      # ★나머지는 기계가 스스로 세운다
        for q in 질문만들기(c, d):
            q["씨앗"] = "자동"
            질문들.append(q)

    닿음, 구멍 = [], []
    종착수 = Counter()
    for q in 질문들:
        후보 = 답후보(코퍼스, q["질문"], q["주어"]) if 코퍼스 else []
        q["후보수"] = len(후보)
        q["후보"] = 후보
        바닥 = next((c["종착"] for c in 후보 if c["종착"]), None)
        q["종착"] = 바닥
        종착수[바닥 or ("후보만" if 후보 else "구멍")] += 1
        (닿음 if 후보 else 구멍).append(q)

    (DATA / "왜질문.jsonl").write_text(
        "\n".join(json.dumps(q, ensure_ascii=False) for q in 닿음) + "\n", encoding="utf-8")
    (DATA / "왜구멍.jsonl").write_text(
        "\n".join(json.dumps(q, ensure_ascii=False) for q in 구멍) + "\n", encoding="utf-8")

    총 = len(질문들)
    L = ["# 왜 굴착 — 기계가 스스로 물어 바닥까지 판 결과", "",
         "> 운영자 260728: *\"내가 질문 만들어야돼? 그럼 내가 알고리즘 짰지\"*", "",
         f"- 기계가 세운 질문 **{총:,}개** (운영자 드릴 씨앗 {len(뿌리질문)} + 자동 {총-len(뿌리질문):,})",
         f"- 코퍼스 {len(코퍼스):,}편 · {sum(len(t) for t,_ in 코퍼스):,}자에서 답 후보 탐색", "",
         "## 어디에 닿았나", "", "| 종착 | 질문 수 | 뜻 |", "|---|---:|---|"]
    뜻 = {"공리": "더 물으면 명리 밖 — 바닥", "천문사실": "천문 사실로 환원 — 바닥",
          "이유없음": "후대 부착 — «이유 없음»이 정답(낭설 아님)",
          "후보만": "답 후보는 있는데 바닥까지 못 감 — **더 파야 함**",
          "구멍": "🔴코퍼스에 답이 없다 — **여기가 다음 작업 목록**"}
    for k, v in 종착수.most_common():
        L.append(f"| {k} | {v:,} | {뜻.get(k,'')} |")
    L += ["", "## 🔴구멍 — 92M자에도 답이 없는 질문 (상위 40)", "",
          "이 목록이 곧 다음에 수집·정제해야 할 것이다. 답을 **짓지 않고** 비워 둔다.", ""]
    for q in 구멍[:40]:
        L.append(f"- [{q['갈래']}] **{q['주어']}** — {q['질문']}"
                 + ("  ⭐운영자 드릴" if q.get("씨앗") == "운영자드릴" else ""))
    L += ["", "## 씨앗 질문(운영자 드릴)의 답 — 실제로 뭐가 나왔나", ""]
    for q in [x for x in 닿음 if x.get("씨앗") == "운영자드릴"]:
        L.append(f"### {q['주어']} — {q['질문']}")
        L.append(f"- 종착: **{q['종착'] or '미도달(후보만)'}**")
        for c in q["후보"][:2]:
            L.append(f"  - `{c['출처']}` — {c['구간'][:220]}")
        L.append("")
    (DATA / "왜굴착_리포트.md").write_text("\n".join(L) + "\n", encoding="utf-8")

    print(f"질문 {총:,}개 · 답 후보 있음 {len(닿음):,} · 🔴구멍 {len(구멍):,}")
    print(f"  종착: {dict(종착수.most_common())}")
    return 총, 종착수, 구멍


if __name__ == "__main__":
    상한 = int(sys.argv[1]) if len(sys.argv) > 1 else None
    main(상한)
