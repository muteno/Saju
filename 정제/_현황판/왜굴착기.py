"""★왜 굴착기 — **스스로 「왜?」를 만들어 바닥까지 판다.**

═══ 왜 이게 생겼나 (운영자 260728, 축자) ═══
  *"내가 질문 만들어야돼? 그럼 내가 알고리즘 짰지"*
  *"모르지? 다시 돌아가"* (× 9회 — 12지·60갑자·용·진토·음양순환 전부 DB 밖이었다)

  그전까지 이 프로젝트가 한 일 = **운영자가 던진 「왜?」에 내가 답하기.**
  그건 알고리즘이 아니라 받아쓰기다. 사람이 질문을 만들어야 하면 자동화가 아니다.
  그래서 이 파일은 **질문을 기계가 만든다.** 노드·주장마다 「왜?」를 세우고,
  코퍼스에서 답을 찾고, **답에 다시 「왜?」를 세워** 바닥에 닿을 때까지 내려간다.

═══ 바닥이 어디냐 — 종착은 딱 셋뿐이다 (260728 운영자 드릴로 확정) ═══
  ① **공리**    — 더 물으면 명리 밖 (음양이 갈린다 · 오행이 다섯 · 天開於子)
  ② **천문사실** — 목성 공전 11.86년≈12 · 황도 15° 등분 · 삭망월 12 · 자전 12시진
  ③ **이유없음** — 후대에 붙은 이름표. **「이유 없다」가 정답이다.**
       12지 동물 배속이 표본 — 여기서 억지 이유를 지어내면 그게 낭설이고 할루시네이션이다.
       ⚠③을 «낭설»과 한 통에 넣으면 안 된다. 낭설 = 이유가 있어야 하는데 못 댐.
          이유없음 = 애초에 이유가 없는 게 참. 정반대다.

  셋 중 어디에도 안 닿으면 **④구멍** — 이게 다음에 파야 할 자리다.
  구멍을 「미검증」으로 덮지 않고 **질문 문장 그대로** 남긴다(조용한 누락 금지).

═══ 무엇을 만들지 않는가 ═══
  답을 **짓지 않는다.** 코퍼스에 후보가 없으면 «구멍»이라고 적고 끝낸다.
  운영자 축자: *"그 사람들이 말한다고 그게 100%가 아냐, 그걸 알려면 왜 그런지를 알아야된다"*
  → 후보를 찾아 놓기까지가 이 파일 몫이고, 참·거짓 판정은 사람·평의회 몫이다.

출력: data/왜질문.jsonl · data/왜구멍.jsonl · data/왜굴착_리포트.md
"""
