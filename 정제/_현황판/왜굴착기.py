def 질문만들기(노드, 정의):
    """노드 하나에서 「왜?」를 세운다. 사람이 안 물어도 기계가 묻는다."""
    out = []
    d = (정의 or "").strip()
    for _, 문형, 갈래 in 질문틀:
        out.append({"주어": 노드, "질문": 문형.format(주어=노드), "갈래": 갈래})
    # 정의문 안의 «~때문·~이라서»가 이미 답을 품고 있으면 한 단 더 판다
    for m in re.finditer(r"([^.。]{4,40}?)(때문|이라서|므로|어서)", d):
        조각 = m.group(1).strip()
        if len(조각) >= 4:
            out.append({"주어": 노드, "질문": f"왜 {조각}인가?", "갈래": "재귀"})
    return out


# ══════════════════════════════════════════════════════════════════
# ③ 답 후보 탐색 — 코퍼스에서 «왜»가 실린 구간을 끌어온다
# ══════════════════════════════════════════════════════════════════
왜표지 = re.compile(r"(왜냐하면|때문이|때문에|그래서|이유는|까닭|~거든요|거든요|인\s*거예요|것이다)")
_공백 = re.compile(r"\s+")


def _키워드(질문, 주어):
    """질문에서 검색 키 뽑기 — 주어 + 질문 고유 명사."""
    키 = {re.sub(r"\(.*?\)", "", 주어).strip()}
    for w in re.findall(r"[가-힣]{2,}", 질문):
        if w not in ("무엇", "경우", "성질", "갈래", "근거", "조건", "예외", "계산", "역할"):
            키.add(w)
    return [k for k in 키 if len(k) >= 2]


def 답후보(코퍼스, 질문, 주어, 상한=3):
    """코퍼스에서 이 질문의 답 후보 구간을 찾는다. **없으면 빈 리스트 — 짓지 않는다.**"""
    키 = _키워드(질문, 주어)
    if not 키:
        return []
    주키 = 키[0]
    out = []
    for 텍스트, 출처 in 코퍼스:
        for m in re.finditer(re.escape(주키), 텍스트):
            seg = 텍스트[max(0, m.start() - 100): m.end() + 260]
            if not 왜표지.search(seg):
                continue
            맞은키 = sum(1 for k in 키 if k in seg)
            if 맞은키 < 2:            # 주어만 스쳐도 답이 아니다 — 최소 2키 교차
                continue
            out.append({"출처": 출처, "구간": _공백.sub(" ", seg)[:320], "키교차": 맞은키,
                        "종착": 종착(seg)})
            if len(out) >= 상한 * 4:
                break
    out.sort(key=lambda r: (-r["키교차"], 0 if r["종착"] else 1))
    return out[:상한]


def 코퍼스적재(뿌리, 상한파일=None):
    """전사 .md 전수 적재(NFC 정규화 — CJK 호환한자·자모분리 방지)."""
    # ⚠260728 실측 함정: 파일이 «전사/채널/채널/파일.md» 3단에 있다(중첩 동명 폴더).
    #   glob("*/*.md")로 잡으면 5,044편 중 249편(5%)만 읽고도 조용히 성공한다.
    fs = sorted(str(x) for x in 뿌리.rglob("*.md"))
    if 상한파일:
        fs = fs[:상한파일]
    out = []
    for f in fs:
        try:
            t = Path(f).read_text(encoding="utf-8", errors="ignore")
        except Exception:
            continue
        out.append((unicodedata.normalize("NFC", _공백.sub(" ", t)), Path(f).parent.name + "/" + Path(f).name))
    return out


