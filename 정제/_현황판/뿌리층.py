# 검증 — 뿌리 없는 항목은 못 들어온다
# ══════════════════════════════════════════════════════════════════════════
def 검증(노드들):
    """모든 항목이 부모를 타고 종착에 닿는가. 안 닿으면 이름을 대고 exit 1."""
    idx = {n["id"]: n for n in 노드들}
    문제 = []
    for n in 노드들:
        for p in n["부모"]:
            if p not in idx:
                문제.append(f"{n['id']}({n['이름']}) 부모 «{p}» 없음")
        if not n["부모"] and not n["종착"]:
            문제.append(f"{n['id']}({n['이름']}) 부모도 종착도 없음 — 공중부양")

    def 바닥까지(nid, 본것=None):
        본것 = 본것 or set()
        if nid in 본것:
            return None                      # 순환 — 바닥 아님
        본것.add(nid)
        n = idx[nid]
        if n["종착"]:
            return n["종착"]
        for p in n["부모"]:
            r = 바닥까지(p, set(본것))
            if r:
                return r
        return None

    for n in 노드들:
        if not 바닥까지(n["id"]):
            문제.append(f"{n['id']}({n['이름']}) 바닥에 안 닿음 — 부모를 타도 종착이 없다")
    return 문제


def 검산():
    """«계산»이라 적은 것은 실제로 계산해 본다. 적어만 놓고 안 돌리면 그게 은폐다."""
    from math import gcd
    r = []
    r.append(("60갑자 = lcm(10,12)", 10 * 12 // gcd(10, 12), 60))
    r.append(("천간 = 오행5 × 음양2", 5 * 2, 10))
    r.append(("십신 = 생극5 × 음양2", 5 * 2, 10))
    r.append(("절기 간격 = 360/24", 360 // 24, 15))
    r.append(("목성 12차 (11.862 반올림)", round(11.862), 12))
    r.append(("삭망 한해당 (365.2422/29.53 반올림)", round(365.2422 / 29.53), 12))
    r.append(("12지 오행배속 칸수 (목2화2금2수2토4)", 2 + 2 + 2 + 2 + 4, 12))
    r.append(("사주 글자수 = 4주 × 2", 4 * 2, 8))
    return [(이름, 실제, 기대, 실제 == 기대) for 이름, 실제, 기대 in r]


